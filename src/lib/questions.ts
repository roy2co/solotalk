/**
 * מכסת השאלות לכל עומק - **מקסימום**, לא מספר קבוע.
 * הברכה הסוגרת נוספת **מעל** המכסה הזו (ראו `selectQuestions`).
 */
/**
 * הכמות **נגזרת מהקונפיג** ולא קבועה בקוד, כדי שאפשר יהיה לכוונן בין
 * אירועים מהדשבורד. `many` (פריסטייל) מקבל מכסה גבוהה מלאכותית — שם
 * המגבלה האמיתית היא **הזמן**, ולא מספר השאלות.
 */
export function questionCount(depth: Depth, cfg?: { depthSettings?: DepthSettings }): number {
  const s = { ...DEFAULT_DEPTH_SETTINGS, ...(cfg?.depthSettings ?? {}) };
  if (depth === 'blessing') return 0;
  if (depth === 'few') return Math.max(1, Math.round(s.fewCount));
  return FREESTYLE_POOL;
}

/**
 * מכסת הפריסטייל. גבוהה בכוונה — רועי אישר שאיש לא מגיע ל-15 שאלות
 * לפני שתקרת הזמן נגמרת, ולכן זו תקרה תיאורטית שנועדה רק למנוע מאגר ריק.
 */
const FREESTYLE_POOL = 40;

function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export interface SelectedQuestions {
  /** השאלות שיוצגו בפועל - באורך questionCount(depth) + הברכה */
  questions: string[];
  /** יתרת המאגר המתאים - מלאי ל"להחליף שאלה" במסך הצילום */
  spares: string[];
}

/**
 * בוחר את השאלות לסשן: מסנן לפי הקרבה שהאורח בחר, ולוקח כמות אקראית לפי העומק.
 *
 * **הברכה תמיד אחרונה, לכל אורח, בלי יוצא מן הכלל** - והיא נוספת **מעל**
 * המכסה. כלומר «עד 8 שאלות» = עד 8 + ברכה. במצב «רק לברך» המכסה היא 0
 * ולכן נשארת הברכה בלבד, בלי צורך במקרה מיוחד.
 *
 * הברכה **לא נכנסת ל-`spares`** - אסור שאפשר יהיה «להחליף» אותה.
 */
export function selectQuestions(
  config: AppConfig,
  relationships: Relationship[],
  depth: Depth,
): SelectedQuestions {
  const blessing = config.blessingPrompt || 'אמרו כמה מילים מהלב 💛';
  const count = questionCount(depth, config);

  if (count === 0) {
    return { questions: [blessing], spares: [] };
  }

  const pool: Question[] = [
    ...(config.useGenericQuestions ? config.genericQuestions : []),
    ...(config.useCustomQuestions ? config.customQuestions : []),
    ...(config.useHardcoreQuestions ? (config.hardcoreQuestions ?? []) : []),
  ].filter((q) => q.text.trim());

  // קטגוריה בלעדית מקבלת **רק** את השאלות שלה - בלי כל השאר.
  // בלי זה הזוג היה מקבל שאלות שנכתבו מנקודת מבט של אורח עליהם.
  const exclusive = relationships.filter((r) =>
    EXCLUSIVE_CATEGORIES.includes(r),
  );

  let matching = exclusive.length
    ? pool.filter((q) => q.relationships.some((r) => exclusive.includes(r)))
    : pool.filter(
        (q) =>
          q.relationships.length === 0 ||
          q.relationships.some((r) => relationships.includes(r)),
      );

  // fallback: אם אין שאלות מתאימות לקרבה, ניקח מכל המאגר; אם ריק לגמרי - ברכה
  if (matching.length === 0) matching = pool;
  if (matching.length === 0) {
    return { questions: [blessing], spares: [] };
  }

  // ערבוב אחד: ההתחלה = השאלות שיוצגו, השארית = הרזרבה (לכן אין חפיפה)
  const ordered = shuffle(matching).map((q) => q.text.trim());
  return {
    questions: [...ordered.slice(0, count), blessing],
    spares: ordered.slice(count),
  };
}
