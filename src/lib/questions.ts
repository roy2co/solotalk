// יוצר שאלה חדשה עם מזהה ייחודי
export function newQuestion(
  text = '',
  relationships: Relationship[] = [],
): Question {
  return {
    id: `q_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
    text,
    relationships,
  };
}

